"""
Industrial Robot Post-Processor (Visual Components / OLP style).
Translates the taught RobotProgram routine into standard industrial robot languages:
1. Standalone Arduino Firmware (.ino) - runs without PC connection
2. G-Code (CNC / 3D Dispensing / Laser / Welding standard)
3. ABB RAPID (MoveJ / MoveL industrial automation)
4. KUKA KRL (PTP / LIN industrial automation)
"""
from typing import List
from src.core.program import RobotProgram, MotionStatement, GripperStatement, DelayStatement
from src.core.kinematics import RobotKinematics


class RobotPostProcessor:
    """Exports taught OLP trajectories into standard industrial robot programs."""

    @staticmethod
    def to_arduino_sketch(program: RobotProgram) -> str:
        """Generates standalone Arduino C++ code to run the routine independently."""
        cpp = []
        cpp.append("// -------------------------------------------------------------")
        cpp.append(f"// Standalone Autonomous Routine: {program.name}")
        cpp.append("// Generated by Robot OLP Studio (Visual Components OLP Engine)")
        cpp.append("// -------------------------------------------------------------\n")
        cpp.append("#include <Servo.h>\n")
        cpp.append("Servo servos[6];")
        cpp.append("const int servoPins[6] = {2, 3, 4, 5, 6, 7};\n")

        # Compile steps
        steps = []
        for stmt in program.statements:
            if isinstance(stmt, MotionStatement):
                steps.append(f"  {{ {', '.join(str(a) for a in stmt.angles)} }}, // {stmt.statement_type} {stmt.target_id}")
            elif isinstance(stmt, GripperStatement):
                # Repeat current pose but with gripper updated
                steps.append(f"  // Gripper {stmt.action} (Jaw: {stmt.target_angle} deg)")
            elif isinstance(stmt, DelayStatement):
                steps.append(f"  // Delay {stmt.duration_ms} ms")

        cpp.append(f"const int ROUTINE_STEPS = {len(steps)};")
        cpp.append("const int routine[ROUTINE_STEPS][6] = {")
        cpp.extend(steps)
        cpp.append("};\n")

        cpp.append("void setup() {")
        cpp.append("  for (int i = 0; i < 6; i++) {")
        cpp.append("    servos[i].attach(servoPins[i]);")
        cpp.append("  }")
        cpp.append("}\n")

        cpp.append("void loop() {")
        cpp.append("  for (int s = 0; s < ROUTINE_STEPS; s++) {")
        cpp.append("    for (int j = 0; j < 6; j++) {")
        cpp.append("      servos[j].write(routine[s][j]);")
        cpp.append("    }")
        cpp.append("    delay(1500); // Step interpolation interval")
        cpp.append("  }")
        cpp.append("  delay(3000); // Pause before repeating routine")
        cpp.append("}")

        return "\n".join(cpp)

    @staticmethod
    def to_gcode(program: RobotProgram, kinematics: RobotKinematics) -> str:
        """Exports Cartesian path as standard industrial G-Code (ISO 6983)."""
        gcode = []
        gcode.append("; -------------------------------------------------------------")
        gcode.append(f"; Program: {program.name}")
        gcode.append("; Standard G-Code Export for CNC, Welding & Dispensing")
        gcode.append("; -------------------------------------------------------------")
        gcode.append("G21 ; Metric units (mm)")
        gcode.append("G90 ; Absolute positioning")
        gcode.append("G92 X0 Y0 Z0 ; Set work coordinate system\n")

        feedrate = 1200
        for i, stmt in enumerate(program.statements):
            if isinstance(stmt, MotionStatement):
                pose = kinematics.forward_kinematics([float(a) for a in stmt.angles])
                cmd = "G1" if stmt.statement_type == "LIN" else "G0"
                f_str = f" F{feedrate}" if cmd == "G1" else ""
                gcode.append(f"{cmd} X{pose.tcp_x:.2f} Y{pose.tcp_y:.2f} Z{pose.tcp_z:.2f}{f_str} ; {stmt.target_id}")
            elif isinstance(stmt, GripperStatement):
                # M-code for actuator (e.g. M3 = Tool On/Close, M5 = Tool Off/Open)
                m_cmd = "M3 ; Tool On / Close Gripper" if stmt.action == "CLOSE" else "M5 ; Tool Off / Open Gripper"
                gcode.append(m_cmd)
            elif isinstance(stmt, DelayStatement):
                gcode.append(f"G4 P{stmt.duration_ms} ; Dwell {stmt.duration_ms} ms")

        gcode.append("\nM30 ; Program End & Rewind")
        return "\n".join(gcode)

    @staticmethod
    def to_abb_rapid(program: RobotProgram, kinematics: RobotKinematics) -> str:
        """Exports routine as industrial ABB RAPID robot code."""
        rapid = []
        rapid.append("MODULE MainModule")
        rapid.append(f"  PROC {program.name}()")

        for stmt in program.statements:
            if isinstance(stmt, MotionStatement):
                pose = kinematics.forward_kinematics([float(a) for a in stmt.angles])
                cmd = "MoveL" if stmt.statement_type == "LIN" else "MoveJ"
                speed = f"v{int(stmt.speed_percent * 10)}"
                p_str = f"[[{pose.tcp_x:.1f}, {pose.tcp_y:.1f}, {pose.tcp_z:.1f}], [1, 0, 0, 0], [0, 0, 0, 0], [9E9, 9E9, 9E9, 9E9, 9E9, 9E9]]"
                rapid.append(f"    {cmd} {p_str}, {speed}, fine, tool0\\WObj:=wobj0; ! {stmt.target_id}")
            elif isinstance(stmt, GripperStatement):
                sig = "1" if stmt.action == "CLOSE" else "0"
                rapid.append(f"    SetDO do_gripper, {sig}; ! {stmt.action}")
            elif isinstance(stmt, DelayStatement):
                rapid.append(f"    WaitTime {stmt.duration_ms / 1000.0:.2f};")

        rapid.append(f"  ENDPROC")
        rapid.append("ENDMODULE")
        return "\n".join(rapid)
